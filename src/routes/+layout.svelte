<script lang="ts">
	import { onNavigate } from '$app/navigation';
	import { Toaster } from '#lib/components/ui/sonner/index.js';
	import { pwaInfo } from 'virtual:pwa-info';
	import '../app.css';

	let { children } = $props();

	onNavigate((navigate) => {
		if (!document.startViewTransition) return;
		// Query-only updates (search, filters) shouldn't animate the whole page
		if (navigate.from?.url.pathname === navigate.to?.url.pathname) return;

		return new Promise((resolve) => {
			document.startViewTransition(async () => {
				resolve();
				await navigate.complete;
			});
		});
	});
</script>

<svelte:head>
	{#if pwaInfo}
		<!-- eslint-disable svelte/no-at-html-tags -- tags are generated by the PWA plugin at build time -->
		{@html pwaInfo.webManifest.linkTag}
		{@html pwaInfo.registerSW?.scriptTag}
		<!-- eslint-enable svelte/no-at-html-tags -->
	{/if}
</svelte:head>

<Toaster />
{@render children()}
